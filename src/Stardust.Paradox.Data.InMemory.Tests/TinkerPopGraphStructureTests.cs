        [Fact]
        public async Task Vertex_WithoutEdges_ShouldBeOrphan()
        {
            var connector = InMemoryGremlinLanguageConnector.Create();
            await connector.ExecuteAsync("g.addV('person').property('id', 'isolated')", new Dictionary<string, object>());
            
            var outResult = await connector.ExecuteAsync("g.V('isolated').out()", new Dictionary<string, object>());
            var inResult = await connector.ExecuteAsync("g.V('isolated').in()", new Dictionary<string, object>());
            
            outResult.Should().BeEmpty();
            inResult.Should().BeEmpty();
        }

        [Fact]
        public async Task Vertex_Delete_ShouldAlsoDeleteEdges()
        {
            var connector = InMemoryGremlinLanguageConnector.Create();
            await connector.ExecuteAsync("g.addV('person').property('id', 'a')", new Dictionary<string, object>());
            await connector.ExecuteAsync("g.addV('person').property('id', 'b')", new Dictionary<string, object>());
            await connector.ExecuteAsync("g.V('a').addE('knows').to(g.V('b'))", new Dictionary<string, object>());
            
            // Verify edge exists
            var beforeResult = await connector.ExecuteAsync("g.E().count()", new Dictionary<string, object>());
            ((long)beforeResult.First()).Should().Be(1);
            
            // Delete vertex
            await connector.ExecuteAsync("g.V('a').drop()", new Dictionary<string, object>());
            
            // Edge should be deleted as well
            var afterResult = await connector.ExecuteAsync("g.E().count()", new Dictionary<string, object>());
            ((long)afterResult.First()).Should().Be(0);
        }

