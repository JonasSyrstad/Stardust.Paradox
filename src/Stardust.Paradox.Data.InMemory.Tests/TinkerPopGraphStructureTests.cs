        [Fact]
        public async Task Edge_ShouldAllowBidirectionalTraversal()
        {
            var connector = InMemoryGremlinLanguageConnector.Create();
            await connector.ExecuteAsync("g.addV('person').property('id', 'a').property('name', 'Alice')", new Dictionary<string, object>());
            await connector.ExecuteAsync("g.addV('person').property('id', 'b').property('name', 'Bob')", new Dictionary<string, object>());
            await connector.ExecuteAsync("g.V('a').addE('knows').to(g.V('b'))", new Dictionary<string, object>());
            
            // From A to B
            var forwardResult = await connector.ExecuteAsync("g.V('a').out('knows').values('name')", new Dictionary<string, object>());
            ((string)forwardResult.First()).Should().Be("Bob");
            
            // From B to A (reverse)
            var reverseResult = await connector.ExecuteAsync("g.V('b').in('knows').values('name')", new Dictionary<string, object>());
            ((string)reverseResult.First()).Should().Be("Alice");
        }

