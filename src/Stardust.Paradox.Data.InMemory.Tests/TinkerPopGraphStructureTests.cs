            var result = await connector.ExecuteAsync("g.V().label()", new Dictionary<string, object>());
            ((string)result.First()).Should().Be("person");
        }

        [Fact]
        public async Task Vertex_ShouldSupportMultipleLabels()
        {
            // Note: TinkerPop 3.x supports multiple labels on vertices
            var connector = InMemoryGremlinLanguageConnector.Create();
            
            // Create vertex with label (multi-label is typically achieved by using :: separator or multiple hasLabel filters)
            await connector.ExecuteAsync("g.addV('person').property('id', 'v1')", new Dictionary<string, object>());
            
            var result = await connector.ExecuteAsync("g.V('v1').hasLabel('person')", new Dictionary<string, object>());
            result.Should().HaveCount(1);
